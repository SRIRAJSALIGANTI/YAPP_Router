// 5. Repeat Random Address Sequence (Two packets to the same random address)
// ------------------------------------------------------------------------------
//Inherits from yapp_base_seq for automated objection management
class yapp_repeat_addr_seq extends yapp_base_seq;

  //Factory registration macro
  `uvm_object_utils(yapp_repeat_addr_seq)

  //Standard object constructor
  function new(string name = "yapp_repeat_addr_seq");
    super.new(name);
  endfunction : new

  task body();
    // Local variable to store and transfer the first generated address
    bit [1:0] prev_addr;

    //Informational tracking banner at the very start (UVM_LOW verbosity)
    `uvm_info("SEQ_START", $sfmtf("Executing sequence: %s", get_type_name()), UVM_LOW)

    // Packet 1: Generate a random packet but explicitly restrict it from address 3
    `uvm_do_with(req, { addr != 3; })

    // Capture the randomized address value generated by the solver
    prev_addr = req.addr;

    // Packet 2: Force the next packet to match the captured address exactly
    `uvm_do_with(req, { addr == prev_addr; })
    
  endtask : body

endclass : yapp_repeat_addr_seq

