// 6. Incremental Payload Sequence (Manual item manipulation sequence)
// ------------------------------------------------------------------------------
class yapp_incr_payload_seq extends yapp_base_seq;

  `uvm_object_utils(yapp_incr_payload_seq)

  function new(string name = "yapp_incr_payload_seq");
    super.new(name);
  endfunction : new

  task body();
    `uvm_info("SEQ_START", $sfmtf("Executing sequence: %s", get_type_name()), UVM_LOW)

    // 1. Create a packet to send
    `uvm_create(req)

    // 2. Randomize the packet (This executes constraints and your post_randomize())
    if (!req.randomize()) begin
      `uvm_fatal("RAND_FAIL", "Failed to randomize packet in yapp_incr_payload_seq")
    end

    // 3. Set the payload values to increment from 0 to length - 1
    foreach (req.payload[i]) begin
      req.payload[i] = i;
    end

    // 4. Update parity manually using your exact class logic
    // Since we mutated the payload array above, the old parity value is wrong.
    if (req.parity_type == GOOD_PARITY) begin
      req.parity = req.calc_parity(); // Use your calculation function directly
    end 
    else begin
      // If the randomizer picked BAD_PARITY, maintain an intentional error
      do begin
        req.parity = $urandom;
      end while (req.parity == req.calc_parity());
    end

    // 5. Send it
    `uvm_send(req)

  endtask : body

endclass : yapp_incr_payload_seq

