// 7. Random Packet Count Sequence (Sequence with its own random properties)
// ------------------------------------------------------------------------------
// a. Inherits from yapp_base_seq for automated objection management
class yapp_rnd_seq extends yapp_base_seq;

  // Declare a random sequence property to control execution loop count
  rand int count;

  // Set an internal constraint to bound the sequence execution scope
  constraint count_limit { count inside {[1:10]}; }

  // c. Factory registration macro
  `uvm_object_utils(yapp_rnd_seq)

  // c. Standard object constructor
  function new(string name = "yapp_rnd_seq");
    super.new(name);
  endfunction : new

  task body();
    // b. Informational tracking banner containing BOTH the name and the random count value
    `uvm_info("SEQ_START", $sfmtf("Executing sequence: %s | Generating %0d random packets", get_type_name(), count), UVM_LOW)

    // Generate completely random packets according to the solved count value
    repeat (count) begin
      `uvm_do(req)
    end
  endtask : body

endclass : yapp_rnd_seq

